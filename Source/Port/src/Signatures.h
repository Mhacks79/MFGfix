inline bool VerifySignatures() {
    unsigned wrong=0;
    for (auto& site:signatures) {
        if (!site.length) {
            if (!Readable(reinterpret_cast<void*>(site.address),4)) { Log("unreadable global: %s",site.name); ++wrong; }
        } else if (memcmp(reinterpret_cast<void*>(site.address),site.bytes,site.length)) {
            Log("signature differs: %s at %08X",site.name,site.address); ++wrong;
        }
    }
    // Hook sites require exact prologues: an unknown existing hook cannot be
    // safely relocated by the small proven trampoline. Reject explicitly.
    const bool hooksOK=!memcmp(reinterpret_cast<void*>(signatures[0].address),signatures[0].bytes,signatures[0].length) &&
                       !memcmp(reinterpret_cast<void*>(signatures[1].address),signatures[1].bytes,signatures[1].length);
    Log("verify: %u sites, %u differences; hook sites %s",unsigned(sizeof(signatures)/sizeof(signatures[0])),wrong,hooksOK?"clear":"conflicting");
    return hooksOK && wrong<3;
}
